-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. STORES / STORE SETTINGS TABLE
CREATE TABLE IF NOT EXISTS stores (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  slug TEXT NOT NULL UNIQUE,
  store_name TEXT NOT NULL DEFAULT 'TASHKENT DRIP',
  description TEXT DEFAULT 'Премиальный streetwear, обувь и селективный парфюм в Ташкенте. Быстрая доставка по всему Узбекистану.',
  avatar_url TEXT DEFAULT 'https://images.unsplash.com/photo-1552374196-1ab2a1c593e8?auto=format&fit=crop&w=400&q=80',
  banner_url TEXT DEFAULT 'https://images.unsplash.com/photo-1558769132-cb1aea458c5e?auto=format&fit=crop&w=1200&q=80',
  instagram_url TEXT DEFAULT 'https://instagram.com/tashkent_drip',
  telegram_username TEXT DEFAULT 'tashkent_drip_order',
  telegram_chat_id TEXT DEFAULT '',
  phone TEXT DEFAULT '+998 90 123 45 67',
  currency TEXT DEFAULT 'сум',
  delivery_info TEXT DEFAULT 'Быстрая доставка по Ташкенту (2-4 часа) и экспресс по регионам Узбекистана (1-2 дня).',
  accent_color TEXT DEFAULT '#171717',
  theme TEXT DEFAULT 'light' CHECK (theme IN ('light', 'dark')),
  catalog_layout TEXT DEFAULT 'grid' CHECK (catalog_layout IN ('grid', 'list')),
  hide_branding BOOLEAN DEFAULT FALSE,
  is_verified BOOLEAN DEFAULT FALSE,
  plan TEXT DEFAULT 'start' CHECK (plan IN ('start', 'plus', 'pro')),
  theme_settings JSONB DEFAULT '{"preset":"minimal","accent_color":"#111827","theme":"light","catalog_layout":"grid","radii_preset":"medium","button_text":"cart","show_old_price":true,"announcement_active":false,"announcement_text":"","hide_branding":false}'::jsonb,
  promo_codes JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. CATEGORIES TABLE
CREATE TABLE IF NOT EXISTS categories (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id UUID REFERENCES stores(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  slug TEXT NOT NULL,
  sort_order INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(store_id, slug)
);

-- 3. PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS products (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id UUID REFERENCES stores(id) ON DELETE CASCADE,
  category_id UUID REFERENCES categories(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  description TEXT,
  price NUMERIC NOT NULL CHECK (price >= 0),
  old_price NUMERIC CHECK (old_price IS NULL OR old_price >= 0),
  images TEXT[] DEFAULT '{}',
  variant_type TEXT DEFAULT 'Размер',
  sizes TEXT[] DEFAULT '{}',
  in_stock BOOLEAN DEFAULT TRUE,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. ORDERS TABLE
CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1042) PRIMARY KEY,
  store_id UUID REFERENCES stores(id) ON DELETE CASCADE,
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  delivery_type TEXT NOT NULL CHECK (delivery_type IN ('delivery', 'pickup')),
  address TEXT,
  comment TEXT,
  items JSONB NOT NULL,
  total_price NUMERIC NOT NULL CHECK (total_price >= 0),
  promo_code TEXT,
  discount_amount NUMERIC DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'completed', 'cancelled')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- INDEXES FOR PERFORMANCE
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_stores_slug ON stores(slug);
CREATE INDEX IF NOT EXISTS idx_stores_owner ON stores(owner_id);
CREATE INDEX IF NOT EXISTS idx_categories_store ON categories(store_id);
CREATE INDEX IF NOT EXISTS idx_products_store ON products(store_id);
CREATE INDEX IF NOT EXISTS idx_products_in_stock ON products(store_id, in_stock);
CREATE INDEX IF NOT EXISTS idx_orders_store ON orders(store_id);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON orders(created_at DESC);

-- ==============================================================================
-- CYBERSECURITY & PRIVILEGE ESCALATION PROTECTION TRIGGER
-- Prevents non-service role users from upgrading their own 'plan' or 'is_verified'
-- ==============================================================================
CREATE OR REPLACE FUNCTION protect_store_privileges()
RETURNS TRIGGER AS $$
BEGIN
  -- Block unprivileged modification of plan or verified status
  IF (current_user != 'service_role' AND current_user != 'postgres') THEN
    IF (NEW.plan IS DISTINCT FROM OLD.plan) THEN
      RAISE EXCEPTION 'Privilege escalation blocked: subscription plan can only be updated by the payment service.';
    END IF;
    IF (NEW.is_verified IS DISTINCT FROM OLD.is_verified) THEN
      RAISE EXCEPTION 'Privilege escalation blocked: verified seller badge is managed strictly by BioMart staff.';
    END IF;
  END IF;
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_protect_store_privileges ON stores;
CREATE TRIGGER tr_protect_store_privileges
BEFORE UPDATE ON stores
FOR EACH ROW EXECUTE FUNCTION protect_store_privileges();

-- ==============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================
ALTER TABLE stores ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

-- STORES POLICIES:
-- 1. Public can read stores to view the storefront
CREATE POLICY "Public stores view" ON stores FOR SELECT USING (true);

-- 2. Authenticated owners can create their store
CREATE POLICY "Owners can insert their store" ON stores FOR INSERT 
  TO authenticated WITH CHECK (auth.uid() = owner_id);

-- 3. Authenticated owners can update their own store
CREATE POLICY "Owners can update their store" ON stores FOR UPDATE 
  TO authenticated USING (auth.uid() = owner_id);

-- CATEGORIES POLICIES:
CREATE POLICY "Public categories view" ON categories FOR SELECT USING (true);
CREATE POLICY "Owners can manage categories" ON categories FOR ALL
  TO authenticated USING (
    EXISTS (SELECT 1 FROM stores WHERE stores.id = categories.store_id AND stores.owner_id = auth.uid())
  );

-- PRODUCTS POLICIES:
CREATE POLICY "Public products view" ON products FOR SELECT USING (is_active = true);
CREATE POLICY "Owners can manage products" ON products FOR ALL
  TO authenticated USING (
    EXISTS (SELECT 1 FROM stores WHERE stores.id = products.store_id AND stores.owner_id = auth.uid())
  );

-- ORDERS POLICIES:
-- 1. Public can insert orders (customer checkout)
CREATE POLICY "Public can place orders" ON orders FOR INSERT WITH CHECK (true);

-- 2. Only store owners can view or update their orders
CREATE POLICY "Owners can view and update orders" ON orders FOR SELECT
  TO authenticated USING (
    EXISTS (SELECT 1 FROM stores WHERE stores.id = orders.store_id AND stores.owner_id = auth.uid())
  );

CREATE POLICY "Owners can update order status" ON orders FOR UPDATE
  TO authenticated USING (
    EXISTS (SELECT 1 FROM stores WHERE stores.id = orders.store_id AND stores.owner_id = auth.uid())
  );

